//var es un tipo de variable que se puede llamar y modiificar su vallr en cualquier parte del codigo 

var nombre = "Juan";
console.log(nombre);    

nombre = "Pedro";
console.log(nombre);

//let es un tipo de variable que se puede llamar y modificar su valor pero solo dentro del bloque donde fue declarada

let edad = 25;
console.log(edad);

edad = 30;
console.log(edad);

//const es un tipo de variable que no se puede modificar su valor una vez declarada

const pais = "Mexico";
console.log(pais);

